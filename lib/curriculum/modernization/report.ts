/**
 * Markdown reports for Library Modernization V1, generated from the baseline build. Every number in
 * these reports is computed from the verified extract, the audits and the ledger; nothing is typed in.
 */
import type { LibraryExtractManifest } from "./extract";
import type { BaselineBuild, RepositorySources } from "./build";
import { findingCatalogue, WAVE_SIZE } from "./build";
import { answerLedgerQuestions } from "./ledger";
import { AUDIT_AREAS, AREA_CRITERIA } from "./legacyAudit";

/** Markdown from lines, with exactly one trailing newline. */
const markdown = (lines: readonly string[]) => `${lines.join("\n").trimEnd()}\n`;
const pct = (n: number, d: number) => (d ? `${Math.round((n / d) * 1000) / 10}%` : "–");
const count = <T,>(items: readonly T[], key: (item: T) => string) => items.reduce<Record<string, number>>((out, item) => ({ ...out, [key(item)]: (out[key(item)] ?? 0) + 1 }), {});
const sortDesc = (record: Record<string, number>) => Object.entries(record).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
const table = (header: readonly string[], rows: readonly (readonly (string | number)[])[]) =>
  [`| ${header.join(" | ")} |`, `| ${header.map((_, i) => (i === 0 ? "---" : "---:")).join(" | ")} |`, ...rows.map((row) => `| ${row.join(" | ")} |`)].join("\n");
const TRACKS = ["A_TARGETED_REPAIR", "B_INSTRUCTIONAL_REDESIGN", "C_FULL_REPLACEMENT", "D_GOVERNANCE_HOLD"] as const;
const OUTCOMES = ["PASS_MECHANICAL_CHECKS", "REVISE", "REBUILD_REQUIRED", "BLOCKED_SOURCE_OR_AUTHORITY"] as const;

export function renderInventoryReport(build: BaselineBuild, manifest: LibraryExtractManifest, sources: RepositorySources, cleanupCapturedAt: string | null): string {
  const inv = build.inventory;
  const total = inv.length;
  const grades = Array.from(new Set(inv.map((r) => r.grade))).sort((a, b) => a - b);
  const subjects = sortDesc(count(inv, (r) => r.subject)).map(([s]) => s);
  const withHistory = inv.filter((r) => Object.values(r.dependencies).some((n) => n > 0));
  const learnerHistory = inv.filter((r) => r.dependencies.studentProgress + r.dependencies.learningEvents + r.dependencies.gradedSubmissions + r.dependencies.tutorConversations + r.dependencies.helpFlags > 0);
  const sum = (key: keyof (typeof inv)[number]["dependencies"]) => inv.reduce((n, r) => n + r.dependencies[key], 0);
  const indicators = sortDesc(count(inv.flatMap((r) => r.indicators), (i) => i));
  const cleanup = sortDesc(count(inv.flatMap((r) => r.cleanupPlanV1), (i) => i));
  const lines = [
    "# Library Modernization Inventory V1",
    "",
    `Generated by \`scripts/build-library-modernization.ts\` from a read-only extract of the production catalog. Captured **${manifest.capturedAt}** in a single \`SET TRANSACTION READ ONLY\` transaction (\`transaction_read_only = ${manifest.transactionReadOnly}\`). Extract digest \`${manifest.extractSha256}\`. Nothing was written to any database.`,
    "",
    "Machine-readable data: `curriculum/modernization/v1/inventory.json` (one record per lesson), `tracker.json`, `audit/`, `waves.json`, `ledger/`.",
    "",
    "## What this inventory covers",
    "",
    `- **Production catalog: ${total} lessons** (every \`CurriculumContent\` row; all have contentType \`lesson\`). This is the whole live catalog, not only the ~40 Grade 7 lessons visible in one library view.`,
    `- **Exact revisions:** ${inv.filter((r) => r.revision.id).length} of ${total} have a current \`CurriculumContentRevision\`. Recomputed snapshot hashes match the stored revision hash for ${inv.filter((r) => r.revision.hashVerified).length}; the live row equals its current revision for ${inv.filter((r) => r.revision.liveRowMatchesRevision).length}. Mismatches: ${manifest.revisionHashMismatches} hash, ${manifest.liveRowsDifferingFromCurrentRevision} live-row.`,
    "- **Not in the catalog** (listed so they are never mistaken for it):",
    "",
    table(["Repository source", "Files", "Kind", "Note"], Object.entries(sources).map(([key, value]) => [`\`${key}\``, value.count, value.kind, value.note])),
    "",
    "## Catalog by grade and subject",
    "",
    table(["Grade", ...subjects, "Total"], grades.map((g) => [g, ...subjects.map((s) => inv.filter((r) => r.grade === g && r.subject === s).length || ""), inv.filter((r) => r.grade === g).length])),
    "",
    "## Publication, lifecycle and provenance",
    "",
    table(["Row status", "Lessons"], sortDesc(count(inv, (r) => r.publication.status))),
    "",
    table(["Lifecycle × provenance completeness", "Lessons"], sortDesc(count(inv, (r) => `${r.publication.lifecycleState} / ${r.publication.provenanceCompleteness}`))),
    "",
    table(["Source class (from generator metadata)", "Lessons"], sortDesc(count(inv, (r) => r.source.class))),
    "",
    table(["Generator family (version)", "Lessons"], sortDesc(count(inv, (r) => r.generatorFamily))),
    "",
    `Every current revision except ${inv.filter((r) => r.source.originKind !== "LEGACY_UNKNOWN").length} is a \`BACKFILL_SNAPSHOT\` with origin \`LEGACY_UNKNOWN\`: provenance was not captured when these lessons were generated. Generator metadata in the payload is the only remaining evidence of origin and is reported as such.`,
    "",
    "## Objectives and alignment",
    "",
    table(["Measure", "Lessons"], [
      ["Have ≥1 objective", inv.filter((r) => r.objectives.count > 0).length],
      ["Carry alignment claims", inv.filter((r) => r.objectives.alignmentClaims > 0).length],
      ["Claims resolve to a structured MOE objective id", inv.filter((r) => r.objectives.structuredMoeIds > 0).length],
      ["Claims are LiberiaLearn-invented codes (e.g. `LR-CIV-G1_3-01`)", inv.filter((r) => r.objectives.inventedCodes > 0).length],
      ["Carry WAEC keyword tags", inv.filter((r) => r.objectives.waecTags.length > 0).length],
    ]),
    "",
    table(["Alignment method recorded", "Lessons"], sortDesc(count(inv, (r) => r.objectives.alignmentMethod ?? "(none)"))),
    "",
    "## Format, assessment, media and accessibility",
    "",
    table(["Measure", "Lessons"], [
      ["Primary text field: body", inv.filter((r) => r.format.primaryTextField === "body").length],
      ["Primary text field: lessonContent", inv.filter((r) => r.format.primaryTextField === "lessonContent").length],
      ["Any assessment prompt", inv.filter((r) => r.assessment.questions > 0).length],
      ["Every assessment prompt keyed", inv.filter((r) => r.assessment.questions > 0 && r.assessment.keyed >= r.assessment.questions).length],
      ["Structured quiz", inv.filter((r) => r.assessment.quiz).length],
      ["Rubric", inv.filter((r) => r.assessment.rubric).length],
      ["Hero image", inv.filter((r) => r.media.heroImage).length],
      ["Lab links", inv.filter((r) => r.media.labs > 0).length],
      ["Audio narration assets", inv.filter((r) => r.media.audioAssets > 0).length],
      ["Video supplements", inv.filter((r) => r.media.videoSupplements > 0).length],
      ["Images without alt text", inv.filter((r) => r.accessibility.imagesWithoutAlt > 0).length],
      ["Language other than English", 0],
    ]),
    "",
    `Median learner-facing words per lesson: ${median(inv.map((r) => r.format.learnerWords))}; grades 1-3: ${median(inv.filter((r) => r.grade <= 3).map((r) => r.format.learnerWords))}.`,
    "",
    "## Assignments, scheduled work and learner-history dependencies (counts only)",
    "",
    `${withHistory.length} lessons have at least one dependent row; **${learnerHistory.length} carry learner history** (progress, learning events, submissions, tutor conversations or help flags). These revisions are protected records: modernization never replaces the revision such history refers to.`,
    "",
    table(["Dependency", "Rows", "Lessons"], ([
      "scheduledWork", "scheduledWorkBundlePinned", "studentProgress", "assignments", "homework", "learningEvents", "gradedSubmissions", "teacherLessonAssignments",
      "lessonPlans", "tutorConversations", "helpFlags", "timetableAssignments", "performanceEvents", "curriculumFlags", "lessonVersions", "lessonShares",
      "audioAssets", "videoSupplements", "prerequisiteLinks", "dependentLessons",
    ] as const).map((key) => [key, sum(key), inv.filter((r) => r.dependencies[key] > 0).length])),
    "",
    `Scheduled work reaches at most ${Math.max(...inv.map((r) => r.dependencies.scheduledWorkSchools))} school(s) per lesson (distinct-school count via the class; no school is named).`,
    "",
    "## Duplicate, stale, broken and conflicting indicators",
    "",
    table(["Indicator", "Lessons"], indicators),
    "",
    `Cleanup Plan V1 (plan only, never applied; snapshot ${cleanupCapturedAt ?? "unknown"}) proposes actions for these lessons. They remain proposals:`,
    "",
    table(["Cleanup Plan V1 action", "Lessons"], cleanup.length ? cleanup : [["(none)", 0]]),
    "",
    "## Candidates and replacements",
    "",
    table(["Lesson", "Candidate"], inv.filter((r) => r.modernization.candidate).map((r) => [`\`${r.contentId}\``, r.modernization.candidate!])),
    "",
    `${inv.filter((r) => !r.modernization.candidate).length} lessons have no Curriculum V2 candidate or modernized replacement.`,
    "",
  ];
  return markdown(lines);
}

function median(values: number[]): number {
  if (!values.length) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.floor(sorted.length / 2)];
}

export function renderQualityBaseline(build: BaselineBuild, manifest: LibraryExtractManifest): string {
  const inv = build.inventory;
  const audits = build.audits;
  const total = inv.length;
  const subjects = sortDesc(count(inv, (r) => r.subject)).map(([s]) => s);
  const grades = Array.from(new Set(inv.map((r) => r.grade))).sort((a, b) => a - b);
  const catalogue = findingCatalogue(audits);
  const areaRows = AUDIT_AREAS.map((area, index) => {
    const statuses = count(audits, (a) => a.areas.find((x) => x.area === area)!.status);
    return [`${index + 1}. ${area}`, AREA_CRITERIA[area].join(", "), statuses.MET ?? 0, statuses.PARTIALLY_MET ?? 0, statuses.NOT_MET ?? 0, statuses.AWAITING_INDEPENDENT_REVIEW ?? 0, statuses.NOT_APPLICABLE ?? 0];
  });
  const wave1 = build.waves.filter((w) => w.wave === 1);
  const invById = new Map(inv.map((r) => [r.contentId, r]));
  const lines = [
    "# Library Curriculum Quality Baseline V1",
    "",
    `Every lesson in the production catalog (${total}) audited at its exact current revision against Curriculum Excellence Standard V1 (\`lib/curriculum/excellence/standard.ts\`), extract captured ${manifest.capturedAt}. Per-lesson findings with revision id, content hash, section pointer, evidence and proposed correction: \`curriculum/modernization/v1/audit/grade-NN.json\`; finding texts: \`audit/finding-catalogue.json\`.`,
    "",
    "## How to read this baseline",
    "",
    "- **Mechanical findings** are reproducible from the revision bytes (structure, counts, arithmetic, keys, alt text, alignment ids). **Judgment indicators** are mechanical signals that need an expert (possible mislabel, unsourced statistic, reading level). **Governance findings** are missing authority (no MOE source, ownership, lifecycle).",
    "- Areas needing expert judgment (accuracy of explanations, conceptual depth, grade fit, cultural accuracy, alignment decisions) are `AWAITING_INDEPENDENT_REVIEW` for every lesson: no qualified human has reviewed any of these revisions against Excellence V1.",
    "- The auditor is automated tooling. It is not a reviewer, and its output is never an independent review. Published or APPROVED status is **not** treated as evidence of educational effectiveness: no lesson in the catalog has learning-outcome evidence.",
    "- Tracks are **provisional** (mechanical basis). A curriculum reviewer confirms each track in the ledger (`TRACK_CONFIRMED`).",
    "",
    "## Review outcomes",
    "",
    table(["Outcome", "Lessons", "Share"], [...OUTCOMES.map((o) => [o, audits.filter((a) => a.mechanicalOutcome === o).length, pct(audits.filter((a) => a.mechanicalOutcome === o).length, total)]), ["AWAITING_INDEPENDENT_REVIEW (judgment areas)", total, "100%"]]),
    "",
    "No lesson passes the mechanical checks: every legacy revision lacks misconception-specific feedback, delayed retention and transfer evidence, which Excellence V1 requires (LM-CON-1, LM-ASM-3, GE-TRN-1).",
    "",
    "## Modernization tracks (provisional)",
    "",
    table(["Track", "Lessons", "Share"], TRACKS.map((t) => [t, inv.filter((r) => r.classification.track === t).length, pct(inv.filter((r) => r.classification.track === t).length, total)])),
    "",
    table(["Held lessons: track once the hold is resolved", "Lessons"], sortDesc(count(inv.filter((r) => r.classification.track === "D_GOVERNANCE_HOLD"), (r) => r.classification.trackAfterHold ?? "–"))),
    "",
    "### Track by subject",
    "",
    table(["Subject", ...TRACKS.map((t) => t.slice(0, 1)), "Total"], subjects.map((s) => [s, ...TRACKS.map((t) => inv.filter((r) => r.subject === s && r.classification.track === t).length), inv.filter((r) => r.subject === s).length])),
    "",
    "### Track by grade",
    "",
    table(["Grade", ...TRACKS.map((t) => t.slice(0, 1)), "Total"], grades.map((g) => [g, ...TRACKS.map((t) => inv.filter((r) => r.grade === g && r.classification.track === t).length), inv.filter((r) => r.grade === g).length])),
    "",
    "## The 18 audit areas",
    "",
    table(["Area", "Excellence criteria", "MET", "PARTIAL", "NOT_MET", "AWAITING_REVIEW", "N/A"], areaRows),
    "",
    "## Findings by code",
    "",
    table(["Code", "Severity", "Kind", "Area", "Lessons"], Object.entries(catalogue).sort((a, b) => b[1].lessons - a[1].lessons).map(([key, entry]) => [key.split("|")[0], key.split("|")[1], entry.kind, entry.area, entry.lessons])),
    "",
    "## Governance holds",
    "",
    table(["Hold reason", "Lessons"], sortDesc(count(audits.flatMap((a) => Array.from(new Set(a.findings.filter((f) => f.kind === "GOVERNANCE" && f.severity === "BLOCKING").map((f) => f.code)))), (c) => c))),
    "",
    "- `NO_MOE_SOURCE_FOR_SUBJECT`: Computer Science and Engineering have no MOE curriculum document in the verified archives (`curriculum/sources/raw/source-manifest.json`). Their objectives are LiberiaLearn-originated and must not be presented as MOE requirements. Unblocking needs a curriculum-owner scope decision, not more generation.",
    "- Civics has no MOE document either; it is traced through MOE Social Studies only as a **proxy** that needs an owner decision before release (`PROXY_SUBJECT_DECISION_REQUIRED`, not a hold).",
    "- WAEC: the repository's WAEC syllabus map comes from public aggregator sources and keyword tagging, so no lesson can claim WAEC alignment beyond \"topic may be relevant\" until an official syllabus is registered.",
    "",
    "## Priority (first proposed wave)",
    "",
    `Priority = (risk × curriculum importance + learner exposure + 2 × prerequisite dependants) / √effort. Risk weighs mechanical severity and accuracy indicators; importance weights foundational literacy and numeracy, most in early grades; exposure uses counts of progress, scheduled work, learning events, schools and assignments. Waves of ${WAVE_SIZE} first take the top lesson of every uncovered grade/subject cell, then fill by score. Held lessons are not scheduled.`,
    "",
    table(["#", "Lesson", "Cell", "Track", "Score", "Why (top findings)"], wave1.slice(0, 25).map((w) => {
      const r = invById.get(w.contentId)!;
      const audit = audits.find((a) => a.contentId === w.contentId)!;
      const top = Array.from(new Set(audit.findings.filter((f) => f.severity === "BLOCKING" || f.severity === "MAJOR").map((f) => f.code))).slice(0, 3).join(", ");
      return [w.rank, `\`${w.contentId}\``, `G${r.grade} ${r.subject}`, w.track.slice(0, 1), w.score, top];
    })),
    "",
    `Full order: \`curriculum/modernization/v1/waves.json\` (${build.waves.length} schedulable lessons in ${Math.max(0, ...build.waves.map((w) => w.wave))} waves).`,
    "",
  ];
  return markdown(lines);
}

export function renderLedgerDashboard(build: BaselineBuild): string {
  const a = answerLedgerQuestions(build.ledger);
  const lines = [
    "# Library Modernization Dashboard",
    "",
    `Generated from the modernization ledger (\`curriculum/modernization/v1/ledger/events.jsonl\`, ${build.ledger.events.length} events, head \`${build.ledger.head}\`). Regenerate with \`npx tsx scripts/build-library-modernization.ts\`; verify with \`npx tsx scripts/verify-library-modernization-ledger.ts\`.`,
    "",
    table(["Question", "Answer"], [
      ["What is live?", `${a.live.observed} lessons observed live (${sortDesc(a.live.byStatus).map(([k, v]) => `${k} ${v}`).join(", ")}); modernized releases: ${a.live.modernizedReleased}`],
      ["What is deficient?", `${a.deficient.audited} audited (${a.deficient.staleAudits} stale): ${sortDesc(a.deficient.byReviewOutcome).map(([k, v]) => `${k} ${v}`).join(", ")}`],
      ["Which track?", sortDesc(a.deficient.byTrack).map(([k, v]) => `${k} ${v}`).join(", ")],
      ["What is on hold?", `${a.onHold}`],
      ["What is being rebuilt?", `scheduled ${a.beingRebuilt.scheduled}, in progress ${a.beingRebuilt.inProgress}, candidate ready ${a.beingRebuilt.candidateReady}, changes requested ${a.beingRebuilt.changesRequested}`],
      ["What awaits independent review?", `${a.awaitingIndependentReview}`],
      ["What is approved?", `review accepted ${a.approved.reviewAccepted}, release authorized ${a.approved.releaseAuthorized}, released ${a.approved.released}`],
      ["What has demonstrated learning?", `${a.demonstratedLearningSuccess} (outcome statuses: ${sortDesc(a.outcomes).map(([k, v]) => `${k} ${v}`).join(", ")})`],
    ]),
    "",
    "## Ledger stages",
    "",
    table(["Stage", "Lessons"], sortDesc(a.byStage)),
    "",
    "## Lessons past the baseline",
    "",
    table(["Lesson", "Stage", "Candidate", "Hash"], Array.from(build.ledger.lessons.values()).filter((s) => s.candidate || s.work).map((s) => [`\`${s.contentId}\``, s.stage, s.candidate ? `${s.candidate.candidateId} ${s.candidate.candidateVersion}` : "–", s.candidate ? `\`${s.candidate.candidateHash.slice(0, 12)}…\`` : "–"])),
    "",
  ];
  return markdown(lines);
}
