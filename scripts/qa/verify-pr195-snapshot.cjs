const fs = require('node:fs');
const cp = require('node:child_process');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const contractCommit = 'ac196397cb13bd6866879c9f5c24503e5195c61d';
const factoryCommit = '3ef84628fdd03e337a4c7cf0fe92e5ce1e548242';
const get = (commit, path) => cp.execFileSync('git', ['show', `${commit}:${path}`], {maxBuffer: 20 * 1024 * 1024});
const json = (commit, path) => JSON.parse(get(commit, path));
const root = 'curriculum/modernization/v1';
const manifestBytes = get(contractCommit, `${root}/first-ten/manifest.json`);
assert.equal(sha(manifestBytes), '4cb6fb5588f5f840fe8b702f181a051a5838b093c1db82b0ea14d9c4b64ea549');
const manifest = JSON.parse(manifestBytes);
const files = [...manifest.files, ...manifest.advisoryReviews];
for (const file of files) assert.equal(sha(get(contractCommit, file.path)), file.sha256, file.path);
const spec = json(contractCommit, `${root}/first-ten/spec.json`);
const bindings = json(contractCommit, `${root}/first-ten/source-bindings.json`).bindings;
const baseline = json(factoryCommit, 'curriculum/factory-v2/first-ten-baseline.json');
const inventory = JSON.parse(fs.readFileSync(`${root}/inventory.json`));
const counts = {};
for (const lesson of inventory.lessons) counts[lesson.classification.track] = (counts[lesson.classification.track] || 0) + 1;
assert.equal(inventory.lessons.length, 1105);
assert.equal(new Set(inventory.lessons.map(x => x.contentId)).size, 1105);
const lessons = spec.lessons.map(lesson => {
  const binding = bindings.find(x => x.source.contentId === lesson.contentId).source;
  const factory = baseline.lessons.find(x => x.contentId === lesson.contentId);
  assert.ok(factory, lesson.contentId);
  for (const key of ['databaseId', 'contentId', 'revisionId', 'snapshotSha256']) assert.equal(binding[key], factory[key], `${lesson.contentId} ${key}`);
  const record = inventory.lessons.find(x => x.contentId === lesson.contentId);
  assert.equal(record.revision.id, binding.revisionId);
  assert.equal(record.revision.contentHash, binding.snapshotSha256);
  return {key: lesson.key, ...binding, grade: lesson.grade, subject: lesson.subject, factorySourceMatches: true};
});
const priorityIds = ['wk_mca7a_fri_p4', 'wk_mca7a_fri_p3', 'lesson_mca_1'];
const firstThree = priorityIds.map(id => {
  const template = json(factoryCommit, `curriculum/factory-v2/authoring/first-three/${id}.input-template.json`);
  assert.equal(template.inputState, 'TEMPLATE');
  assert.ok(template.resources.every(x => x.payload === null));
  return {source: template.source, inputState: template.inputState, candidateId: null, proposedBlueprintId: template.blueprint.blueprintId, resources: template.resources.length, authoredPayloads: 0, approved: template.approved, published: template.published, released: template.released};
});
const result = {checkedAt: new Date().toISOString(), integrationCommit: cp.execFileSync('git', ['rev-parse', 'HEAD']).toString().trim(), contractCommit, factoryCommit, contractVersion: spec.contractVersion, manifestSha256: sha(manifestBytes), verifiedContractFiles: files.length, inventoryCapture: inventory.extract, classificationCounts: counts, factoryContractVersion: baseline.contractVersion, factorySpecSha256: baseline.specSha256, contractCompatible: false, lessons, firstThree};
fs.writeFileSync('artifacts/pr195-review/contract-inventory.json', JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify({classificationCounts: counts, verifiedContractFiles: files.length, sourceBindingsMatching: lessons.length, firstThreeAuthored: 0, contractCompatible: false}));
